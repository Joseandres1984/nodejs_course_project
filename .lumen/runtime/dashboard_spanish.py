_TOKEN_RE = re.compile(r"(<(?:script|style)\b[^>]*>.*?</(?:script|style)\s*>|<[^>]+>)", re.IGNORECASE | re.DOTALL)


def _translate_visible_text(text: str) -> str:
    out = text
    for source in sorted(TRANSLATIONS, key=len, reverse=True):
        out = out.replace(source, TRANSLATIONS[source])
    return out


def spanishize_dashboard(page: str) -> str:
    parts = _TOKEN_RE.split(page)
    translated = []
    for part in parts:
        if not part:
            continue
        if part.startswith("<"):
            translated.append(part)
        else:
            translated.append(_translate_visible_text(part))
    result = "".join(translated)
    if "<html>" in result:
        result = result.replace("<html>", '<html lang="es">', 1)
    elif "<html " in result and "lang=" not in result.split(">", 1)[0]:
        result = result.replace("<html ", '<html lang="es" ', 1)
    return result
